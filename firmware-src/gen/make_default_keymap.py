#!/usr/bin/env python3
"""Generate the built-in default keymap C header from the captured factory keymap.
Default = HHKB Hybrid JIS factory layout, with A S D F -> H H K B as an "it installed" marker,
keeping Z, /, \\ (Yen/Ro) untouched so macOS keyboard tools still work.

Positions are HID usage IDs; index 69 = top-left (Esc), decreasing left-to-right per row.
A=pos39 S=pos38 D=pos37 F=pos36 (the Control row).  H=0x0B K=0x0E B=0x05.
"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
fk = json.loads((root / "analysis/hhkb-hybrid-jis/factory-keymap.json").read_text())
std = bytearray.fromhex(fk["standard"])
fn = bytearray.fromhex(fk["fn"])
OVER = {39: 0x0B, 38: 0x0B, 37: 0x0E, 36: 0x05}  # A->H S->H D->K F->B
for pos, code in OVER.items():
    std[pos] = code
def carr(b):
    return ",".join(f"0x{x:02x}" for x in b)
out = root / "firmware-src/src/default_keymap.h"
out.write_text(
    "/* Generated by gen/make_default_keymap.py from analysis/hhkb-hybrid-jis/factory-keymap.json.\n"
    " * Default marker: A S D F type H H K B; Z / \\ preserved. Do not edit by hand. */\n"
    "#ifndef HHKB_DEFAULT_KEYMAP_H\n#define HHKB_DEFAULT_KEYMAP_H\n#include <stdint.h>\n"
    "#define HHKB_KEYMAP_LEN 128\n"
    f"static const uint8_t hhkb_default_standard[HHKB_KEYMAP_LEN] = {{{carr(std)}}};\n"
    f"static const uint8_t hhkb_default_fn[HHKB_KEYMAP_LEN] = {{{carr(fn)}}};\n"
    "#endif\n")
print("wrote", out.relative_to(root), "A/S/D/F ->", " ".join(f"{std[p]:#04x}" for p in (39,38,37,36)),
      "| Z,/,\\ =", f"{std[26]:#04x},{std[17]:#04x},{std[16]:#04x}")
