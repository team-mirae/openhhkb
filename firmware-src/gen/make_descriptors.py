#!/usr/bin/env python3
"""Generate USB descriptors for the Hybrid firmware from the captured HID report descriptors.

Device identity and the three HID interfaces come from analysis/hhkb-hybrid-jis/ (our own scan).
Endpoint numbers are our choice (EP1 IN keyboard, EP2 IN multimedia, EP3 IN/OUT vendor).
Emits src/usb_descriptors.h (byte arrays + a few offsets the driver needs).
"""
import pathlib

root = pathlib.Path(__file__).resolve().parents[2]
rd_dir = root / "analysis/hhkb-hybrid-jis/report-descriptors"
rd = {i: (rd_dir / f"input{i}.bin").read_bytes() for i in (0, 1, 2)}

VID, PID, BCD_DEV = 0x04FE, 0x0022, 0x0001


def u16(v):
    return [v & 0xFF, (v >> 8) & 0xFF]


# ---- device descriptor (18 bytes) ----
device = [
    18, 0x01, *u16(0x0110), 0x00, 0x00, 0x00, 64,
    *u16(VID), *u16(PID), *u16(BCD_DEV), 1, 2, 0, 1,
]

# ---- HID interface + endpoint builders ----
def hid_iface(num, subclass, protocol, report_len, eps):
    # interface(9) + HID(9) + endpoints
    iface = [9, 0x04, num, 0, len(eps), 0x03, subclass, protocol, 0]
    hid = [9, 0x21, *u16(0x0111), 0, 1, 0x22, *u16(report_len)]
    epd = []
    for addr, size, interval in eps:
        epd += [7, 0x05, addr, 0x03, *u16(size), interval]
    return iface + hid + epd


# IF0 boot keyboard: subclass 1 (boot), protocol 1 (keyboard), EP1 IN
if0 = hid_iface(0, 1, 1, len(rd[0]), [(0x81, 8, 10)])
# IF1 multimedia + NKRO: subclass 0 protocol 0, EP2 IN (max input report 31 -> 32B EP)
if1 = hid_iface(1, 0, 0, len(rd[1]), [(0x82, 32, 10)])
# IF2 vendor 0xFF00/0x01: EP3 IN + EP3 OUT, 64B
if2 = hid_iface(2, 0, 0, len(rd[2]), [(0x83, 64, 1), (0x03, 64, 1)])

body = if0 + if1 + if2
total = 9 + len(body)
config = [9, 0x02, *u16(total), 3, 1, 0, 0xA0, 50] + body

# ---- strings ----
def strdesc(s):
    b = s.encode("utf-16-le")
    return [len(b) + 2, 0x03, *b]

str0 = [4, 0x03, 0x09, 0x04]  # LANGID en-US
str1 = strdesc("PFU Limited")
str2 = strdesc("HHKB-Hybrid")


def carr(name, data):
    return f"static const uint8_t {name}[{len(data)}] = {{" + ",".join(str(b) for b in data) + "};\n"


out = root / "firmware-src/src/usb_descriptors.h"
txt = ["/* Generated by gen/make_descriptors.py from analysis/hhkb-hybrid-jis/. Do not edit. */\n",
       "#ifndef HHKB_USB_DESCRIPTORS_H\n#define HHKB_USB_DESCRIPTORS_H\n#include <stdint.h>\n"]
txt.append(carr("usb_device_desc", device))
txt.append(carr("usb_config_desc", config))
txt.append(carr("usb_string0", str0))
txt.append(carr("usb_string1", str1))
txt.append(carr("usb_string2", str2))
txt.append(carr("hid_report0", list(rd[0])))
txt.append(carr("hid_report1", list(rd[1])))
txt.append(carr("hid_report2", list(rd[2])))
# offsets of the HID descriptor's wDescriptorLength are implicit; driver serves hid_reportN by interface
txt.append("#define USB_CONFIG_TOTAL " + str(total) + "\n")
txt.append("#endif\n")
out.write_text("".join(txt))
print("wrote", out.relative_to(root), "config wTotalLength =", total,
      "| report desc lens", {i: len(rd[i]) for i in rd})
